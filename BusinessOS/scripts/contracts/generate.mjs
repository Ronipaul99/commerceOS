import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { isDeepStrictEqual } from "node:util";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = new URL("../../", import.meta.url);
const specPath = "packages/api-contracts/openapi.json";
const read = (path) => readFileSync(new URL(path, root), "utf8").replaceAll("\r\n", "\n");
const document = JSON.parse(read(specPath));
const banner = "// Generated by scripts/contracts/generate.mjs. Do not edit.\n";

export function checkCompatibility(previous, current) {
  if (previous.openapi !== current.openapi || !isDeepStrictEqual(previous.security, current.security)) {
    throw new Error("The published OpenAPI version or authorization policy changed");
  }
  for (const [path, item] of Object.entries(previous.paths)) {
    for (const [method, definition] of Object.entries(item)) {
      if (!isDeepStrictEqual(definition, current.paths[path]?.[method])) {
        throw new Error("Published operation changed: " + method.toUpperCase() + " " + path);
      }
    }
  }
  for (const [kind, entries] of Object.entries(previous.components ?? {})) {
    for (const [name, definition] of Object.entries(entries)) {
      if (!isDeepStrictEqual(definition, current.components?.[kind]?.[name])) {
        throw new Error("Published component changed: " + kind + "/" + name);
      }
    }
  }
}

function typeOf(schema) {
  if (schema.$ref) {
    const match = /^#\/components\/schemas\/([A-Z]\w+)$/.exec(schema.$ref);
    if (!match || !Object.hasOwn(document.components.schemas, match[1])) {
      throw new Error("Unsupported schema reference " + schema.$ref);
    }
    return match[1];
  }
  if (Array.isArray(schema.type)) return schema.type.map((type) => typeOf({ type })).join(" | ");
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  switch (schema.type) {
    case "string":
    case "boolean":
    case "null":
      return schema.type;
    case "integer":
    case "number":
      return "number";
    case "array":
      return "Array<" + typeOf(schema.items) + ">";
    case "object": {
      if (!schema.properties) return "Record<string, unknown>";
      const fields = Object.entries(schema.properties).map(([name, field]) =>
        "  " + JSON.stringify(name) + (schema.required.includes(name) ? "" : "?") + ": " + typeOf(field) + ";");
      return "{\n" + fields.join("\n") + "\n}";
    }
    default:
      throw new Error("Unsupported schema type: " + schema.type);
  }
}

function renderContracts(spec) {
  return banner + Object.entries(spec.components.schemas).map(([name, schema]) =>
    "export type " + name + " = " + typeOf(schema) + ";").join("\n\n") + "\n";
}

function renderClient(spec) {
  const operations = [];
  const responseTypes = new Set();
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      if (!["get", "post", "put"].includes(method) || !/^\/api\/v1\/[a-zA-Z/{}-]+$/.test(path)) {
        throw new Error("Unsupported client route: " + method + " " + path);
      }
      if (!/^[a-z][a-zA-Z0-9]+$/.test(operation.operationId)) throw new Error("Invalid operation ID");
      const response = operation.responses["200"] ?? operation.responses["201"];
      const binary = Boolean(response.content["application/octet-stream"]);
      const output = binary ? "ArrayBuffer" : typeOf(response.content["application/json"].schema);
      if (!binary) responseTypes.add(output);
      const parameters = (operation.parameters ?? []).map((parameter) => {
        if (!parameter.$ref) return parameter;
        const name = parameter.$ref.split("/").at(-1);
        if (!Object.hasOwn(spec.components.parameters, name)) throw new Error("Unknown route parameter");
        return spec.components.parameters[name];
      });
      const pathParams = parameters.filter((parameter) => parameter.in === "path");
      const queries = parameters.filter((parameter) => parameter.in === "query");
      const bodySchema = operation.requestBody?.content?.["application/json"]?.schema;
      const input = bodySchema ? typeOf(bodySchema) : undefined;
      if (input) responseTypes.add(input);
      const queryType = queries.length === 0 ? "" : "query: " + typeOf({
        type: "object", properties: Object.fromEntries(queries.map((q) => [q.name, q.schema])),
        required: queries.filter((q) => q.required).map((q) => q.name),
      }).replaceAll("\n", " ") + (queries.some((q) => q.required) ? ", " : " = {}, ");
      const query = queries.length === 0 ? "{}" : "query";
      const args = pathParams.map((parameter) => {
        if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(parameter.name)) throw new Error("Invalid path parameter");
        return parameter.name + ": string, ";
      }).join("");
      let target = JSON.stringify(path);
      for (const parameter of pathParams) {
        target = target.replace("{" + parameter.name + "}", '" + encodeURIComponent(' + parameter.name + ') + "');
      }
      const requestKey = parameters.some((parameter) => parameter.name === "Idempotency-Key");
      const version = parameters.some((parameter) => parameter.name === "If-Match");
      const options = "options: RequestOptions" + (requestKey ? " & { idempotencyKey: string }"
        : version ? " & { ifMatch: string }" : " = {}");
      operations.push("  " + operation.operationId + "(" + args + (input ? "body: " + input + ", " : "")
        + queryType + options + "): Promise<" + output + "> {\n    return this.request("
        + [JSON.stringify(method.toUpperCase()), target, query, "options", input ? "body" : "undefined", String(binary)].join(", ")
        + ");\n  }");
    }
  }
  return banner + "import type { ErrorEnvelope, " + [...responseTypes].join(", ") + ' } from "@businessos/api-contracts";\n\n'
    + read("scripts/contracts/client.template.txt").replace("/* generated operations */", operations.join("\n\n"));
}

function verifyBase(ref) {
  const cwd = fileURLToPath(root);
  const gitRoot = execFileSync("git", ["rev-parse", "--show-toplevel"], { cwd, encoding: "utf8" }).trim();
  const path = execFileSync("git", ["rev-parse", "--show-prefix"], { cwd, encoding: "utf8" }).trim() + specPath;
  // A first publication has no baseline. An invalid base ref still fails.
  const old = execFileSync("git", ["ls-tree", "--name-only", ref, "--", path], { cwd: gitRoot, encoding: "utf8" }).trim();
  if (old) {
    const contents = execFileSync("git", ["show", ref + ":" + path], { cwd: gitRoot, encoding: "utf8" });
    checkCompatibility(JSON.parse(contents), document);
  }
}

function main() {
  const [flag, baseFlag, ref, ...extra] = process.argv.slice(2);
  if ((flag && flag !== "--check") || (baseFlag && (baseFlag !== "--base-ref" || !ref))
      || extra.length || (ref && !/^[a-f0-9]{40}$/i.test(ref))) {
    throw new Error("Usage: node scripts/contracts/generate.mjs [--check [--base-ref <commit sha>]]");
  }
  if (ref) verifyBase(ref);
  for (const [path, content] of [
    ["packages/api-contracts/src/index.ts", renderContracts(document)],
    ["packages/api-client/src/index.ts", renderClient(document)],
  ]) {
    const output = new URL(path, root);
    if (flag === "--check") {
      if (!existsSync(output) || read(path) !== content) {
        throw new Error("Generated contract drift: " + path);
      }
    } else {
      writeFileSync(output, content);
    }
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) main();
